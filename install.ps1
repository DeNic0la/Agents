# Installs the preset for Claude Code, Codex and GitHub Copilot into your home.
# Native Windows; works in Windows PowerShell 5.1 and PowerShell 7.
#
#   .\install.ps1              install (safe to re-run)
#   .\install.ps1 -Update      git pull, then install
#   .\install.ps1 -Uninstall   remove everything that points into this repo
#
# Directories are linked with junctions (no admin needed). Files are symlinked
# when allowed (Developer Mode or admin), otherwise copied: copies are tracked in
# ~\.agents\.copies, refreshed on every run and removed like links.
# AGENTS_NO_SYMLINKS=1 forces copies (used by tests\smoke.ps1).
# The mapping mirrors global_mappings in lib/common.sh - keep the two in sync.
[CmdletBinding()]
param([switch]$Update, [switch]$Uninstall, [string]$HomeDir = $HOME)

$ErrorActionPreference = 'Stop'

if ($Update) {
    Write-Host "Updating $PSScriptRoot"
    # --autostash keeps local edits (e.g. made through ~\.claude) across the pull.
    git -C $PSScriptRoot pull --rebase --autostash
    if ($LASTEXITCODE -ne 0) {
        Write-Error "git pull failed - resolve it in $PSScriptRoot, then run .\install.ps1"
    }
    # Re-run from disk so a changed installer takes effect.
    & (Join-Path $PSScriptRoot 'install.ps1') -HomeDir $HomeDir
    return
}

$Repo = $PSScriptRoot
$Preset = Join-Path $Repo 'preset'
$Tools = Join-Path $Repo 'tools'
$ClaudeHome = if ($env:CLAUDE_CONFIG_DIR) { $env:CLAUDE_CONFIG_DIR } else { Join-Path $HomeDir '.claude' }
$CodexHome = if ($env:CODEX_HOME) { $env:CODEX_HOME } else { Join-Path $HomeDir '.codex' }
$CopilotHome = if ($env:COPILOT_HOME) { $env:COPILOT_HOME } else { Join-Path $HomeDir '.copilot' }
$AgentsHome = Join-Path $HomeDir '.agents'
$Overrides = Join-Path $AgentsHome 'overrides'   # user-owned runtime controls, never touched
$Marker = '.agents-generated'
$BinDir = if ($env:AGENTS_BIN_DIR) { $env:AGENTS_BIN_DIR } else { Join-Path $HomeDir '.local\bin' }
$Stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$GeneratedPattern = '^# Generated by agents from (.+) - edit that file instead\.$'
$CopiesFile = Join-Path $AgentsHome '.copies'

# Files copied because symlinks weren't allowed, as dst -> @{ Hash; Src }. One
# "hash<TAB>src<TAB>dst" line each in $CopiesFile.
$Copies = @{}
if (Test-Path -LiteralPath $CopiesFile) {
    foreach ($line in [System.IO.File]::ReadAllLines($CopiesFile)) {
        $hash, $src, $dst = $line -split "`t"
        if ($dst) { $Copies[$dst] = @{ Hash = $hash; Src = $src } }
    }
}

function Save-Copies {
    if ($Copies.Count -eq 0) {
        if (Test-Path -LiteralPath $CopiesFile) { Remove-Item -LiteralPath $CopiesFile }
        return
    }
    New-Item -ItemType Directory -Force -Path $AgentsHome | Out-Null
    $lines = foreach ($dst in $Copies.Keys | Sort-Object) { "$($Copies[$dst].Hash)`t$($Copies[$dst].Src)`t$dst" }
    [System.IO.File]::WriteAllText($CopiesFile, (($lines -join "`n") + "`n"))
}

function Get-LinkTarget([string]$Path) {
    $item = Get-Item -LiteralPath $Path -Force -ErrorAction SilentlyContinue
    if ($item -and $item.LinkType) { return (@($item.Target)[0] -replace '^\\\\\?\\', '') }
    return $null
}

# Deletes only the link itself, never the contents behind a junction.
function Remove-Link([string]$Path) {
    if ((Get-Item -LiteralPath $Path -Force).PSIsContainer) {
        [System.IO.Directory]::Delete($Path)
    } else {
        [System.IO.File]::Delete($Path)
    }
}

function Move-Aside([string]$Path) {
    Move-Item -LiteralPath $Path -Destination "$Path.bak.$Stamp"
    Write-Host "backup  $Path -> $Path.bak.$Stamp"
}

# Symlinks a file; $false when this machine doesn't allow it (no Developer Mode or admin).
function New-FileLink([string]$From, [string]$To) {
    if ($env:AGENTS_NO_SYMLINKS) { return $false }
    try {
        New-Item -ItemType SymbolicLink -Path $To -Target $From | Out-Null
        return $true
    } catch {}
    # Windows PowerShell 5.1 can't use Developer Mode for symlinks; mklink can. Under 'Stop',
    # 5.1 turns mklink's error output into an exception that would end the install.
    $ErrorActionPreference = 'Continue'
    cmd /c mklink "$To" "$From" 2>&1 | Out-Null
    return ($LASTEXITCODE -eq 0)
}

function Install-Link([string]$From, [string]$To) {
    New-Item -ItemType Directory -Force -Path (Split-Path $To) | Out-Null
    $same = $false   # $To is a file with the same content as $From
    $target = Get-LinkTarget $To
    if ($target) {
        if ($target -eq $From) { Write-Host "ok      $To"; return }
        Remove-Link $To
    } elseif (Test-Path -LiteralPath (Join-Path $To $Marker)) {
        Remove-Item -LiteralPath $To -Recurse -Force
    } elseif (Test-Path -LiteralPath $To) {
        $hash = if (-not (Get-Item -LiteralPath $To -Force).PSIsContainer) { (Get-FileHash -LiteralPath $To).Hash }
        $same = $hash -and $hash -eq (Get-FileHash -LiteralPath $From).Hash
        # Nothing is lost replacing a file identical to the source, or a copy of ours nobody edited.
        if ($same -or ($hash -and $Copies.ContainsKey($To) -and $Copies[$To].Hash -eq $hash)) {
            Remove-Item -LiteralPath $To -Force
        } else {
            Move-Aside $To
        }
    }
    $Copies.Remove($To)

    if ((Get-Item -LiteralPath $From).PSIsContainer) {
        New-Item -ItemType Junction -Path $To -Target $From | Out-Null
        Write-Host "linked  $To"
    } elseif (New-FileLink $From $To) {
        Write-Host "linked  $To"
    } else {
        Copy-Item -LiteralPath $From -Destination $To
        $Copies[$To] = @{ Hash = (Get-FileHash -LiteralPath $To).Hash; Src = $From }
        if ($same) { Write-Host "ok      $To (copy)" }
        else { Write-Host "copied  $To (enable Developer Mode for symlinks)" -ForegroundColor Yellow }
    }
}

function ConvertTo-TomlString([string]$Value) {
    '"' + ($Value -replace '\\', '\\' -replace '"', '\"') + '"'
}

# Codex custom agent (TOML) for a subagent Markdown file; $null if the body can't be stored.
function New-CodexAgent([string]$Src) {
    $lines = [System.IO.File]::ReadAllLines($Src)
    $meta = @{}
    $start = 0
    if ($lines.Count -gt 0 -and $lines[0] -eq '---') {
        for ($i = 1; $i -lt $lines.Count; $i++) {
            if ($lines[$i] -eq '---') { $start = $i + 1; break }
            if ($lines[$i] -match '^([^:]+):\s*(.*?)\s*$' -and -not $meta.ContainsKey($Matches[1])) {
                $meta[$Matches[1]] = $Matches[2] -replace '^["'']|["'']$', ''
            }
        }
    }
    $text = if ($start -lt $lines.Count) { ($lines[$start..($lines.Count - 1)] -join "`n").TrimEnd("`n") } else { '' }
    if ($text.Contains("'''")) { return $null }
    $name = if ($meta['name']) { $meta['name'] } else { [System.IO.Path]::GetFileNameWithoutExtension($Src) }
    "# Generated by agents from $(Split-Path $Src -Leaf) - edit that file instead.`n" +
    "name = $(ConvertTo-TomlString $name)`n" +
    "description = $(ConvertTo-TomlString $meta['description'])`n" +
    "developer_instructions = '''`n$text`n'''`n"
}

function Write-CodexAgent([string]$From, [string]$To) {
    $content = New-CodexAgent $From
    if ($null -eq $content) { Write-Warning "skipped $To (body of $From contains ''')"; return }
    New-Item -ItemType Directory -Force -Path (Split-Path $To) | Out-Null
    if (Test-Path -LiteralPath $To) {
        $current = [System.IO.File]::ReadAllText($To)
        if ($current -eq $content) { Write-Host "ok      $To"; return }
        if ($current -notmatch '^# Generated by agents') { Move-Aside $To }
    }
    [System.IO.File]::WriteAllText($To, $content)
    Write-Host "wrote   $To"
}

# SKILL.md with the top-level keys of the given YAML files (later files win)
# merged into its frontmatter. Mirrors merge_skill_md in lib/common.sh.
function Merge-SkillMd([string]$Base, [string[]]$Files) {
    $blocks = [ordered]@{}
    foreach ($f in $Files) {
        $key = $null
        foreach ($line in [System.IO.File]::ReadAllLines($f)) {
            if ($line -match '^([A-Za-z0-9_-]+):') { $key = $Matches[1]; $blocks[$key] = $line }
            elseif ($key -and $line -match '^[ \t-]') { $blocks[$key] += "`n$line" }
            else { $key = $null }
        }
    }
    $out = New-Object System.Collections.Generic.List[string]
    $lines = [System.IO.File]::ReadAllLines($Base)
    $inFm = $false; $skip = $false
    for ($i = 0; $i -lt $lines.Count; $i++) {
        $line = $lines[$i]
        if ($i -eq 0 -and $line -eq '---') { $inFm = $true; $out.Add($line); continue }
        if ($inFm) {
            if ($line -eq '---') {
                foreach ($v in $blocks.Values) { $out.Add($v) }
                $out.Add($line); $inFm = $false; continue
            }
            if ($line -match '^([A-Za-z0-9_-]+):') { $skip = $blocks.Contains($Matches[1]) }
            if ($skip) { continue }
        }
        $out.Add($line)
    }
    ($out -join "`n") + "`n"
}

function Test-SkillNeedsBuild([string]$Tool, [string]$Src) {
    $n = Split-Path $Src -Leaf
    switch ($Tool) {
        'claude' { (Test-Path (Join-Path $Src 'agents\claude.yaml')) -or (Test-Path (Join-Path $Overrides "claude\$n.yaml")) }
        'codex' { Test-Path (Join-Path $Overrides "codex\$n.yaml") }
        default { $false }
    }
}

# Builds a tool's copy of a skill. Mirrors build_skill in lib/common.sh.
function Build-Skill([string]$Tool, [string]$Src, [string]$Dst) {
    $n = Split-Path $Src -Leaf
    Copy-Item -LiteralPath $Src -Destination $Dst -Recurse
    if ($Tool -eq 'claude') {
        $extra = @((Join-Path $Src 'agents\claude.yaml'), (Join-Path $Overrides "claude\$n.yaml")) | Where-Object { Test-Path -LiteralPath $_ }
        if ($extra) { [System.IO.File]::WriteAllText((Join-Path $Dst 'SKILL.md'), (Merge-SkillMd (Join-Path $Src 'SKILL.md') @($extra))) }
    } elseif ($Tool -eq 'codex') {
        $override = Join-Path $Overrides "codex\$n.yaml"
        if (Test-Path -LiteralPath $override) {
            New-Item -ItemType Directory -Force -Path (Join-Path $Dst 'agents') | Out-Null
            Copy-Item -LiteralPath $override -Destination (Join-Path $Dst 'agents\openai.yaml') -Force
        }
    }
    [System.IO.File]::WriteAllText((Join-Path $Dst $Marker), "$n`n")
}

function Get-TreeHash([string]$Path) {
    (Get-ChildItem -LiteralPath $Path -Recurse -File -Force | Sort-Object FullName | ForEach-Object {
        $_.FullName.Substring($Path.Length) + ':' + (Get-FileHash -LiteralPath $_.FullName).Hash
    }) -join '|'
}

# Links a skill, or builds a marked copy when an adapter or override applies.
function Install-Skill([string]$Tool, [string]$From, [string]$To) {
    if (-not (Test-SkillNeedsBuild $Tool $From)) { Install-Link $From $To; return }
    $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ([System.IO.Path]::GetRandomFileName())
    Build-Skill $Tool $From $tmp
    $generated = Test-Path -LiteralPath (Join-Path $To $Marker)
    if ($generated -and (Get-TreeHash $tmp) -eq (Get-TreeHash $To)) {
        Remove-Item -LiteralPath $tmp -Recurse -Force
        Write-Host "ok      $To"; return
    }
    New-Item -ItemType Directory -Force -Path (Split-Path $To) | Out-Null
    if (Get-LinkTarget $To) { Remove-Link $To }
    elseif ($generated) { Remove-Item -LiteralPath $To -Recurse -Force }
    elseif (Test-Path -LiteralPath $To) { Move-Aside $To }
    Copy-Item -LiteralPath $tmp -Destination $To -Recurse
    Remove-Item -LiteralPath $tmp -Recurse -Force
    Write-Host "built   $To ($Tool adapter/override applied)"
}

function Get-Children([string]$Path, [switch]$Directory) {
    if (-not (Test-Path -LiteralPath $Path)) { return @() }
    Get-ChildItem -LiteralPath $Path -Directory:$Directory | Where-Object { $_.Name -ne '.gitkeep' }
}

# Where every preset item goes, as @(mode, src, dst).
function Get-Mappings {
    $instructions = Join-Path $Preset 'AGENTS.md'
    , @('link', $instructions, (Join-Path $ClaudeHome 'CLAUDE.md'))
    , @('link', $instructions, (Join-Path $CodexHome 'AGENTS.md'))
    , @('link', $instructions, (Join-Path $CopilotHome 'copilot-instructions.md'))
    foreach ($e in Get-Children (Join-Path $Preset 'skills') -Directory) {
        , @('skill-claude', $e.FullName, (Join-Path $ClaudeHome "skills\$($e.Name)"))
        , @('skill-codex', $e.FullName, (Join-Path $AgentsHome "skills\$($e.Name)"))   # Codex + Copilot
    }
    foreach ($e in Get-Children (Join-Path $Preset 'agents') | Where-Object Extension -eq '.md') {
        , @('link', $e.FullName, (Join-Path $ClaudeHome "agents\$($e.Name)"))
        , @('link', $e.FullName, (Join-Path $CopilotHome "agents\$($e.BaseName).agent.md"))
        , @('codex-agent', $e.FullName, (Join-Path $CodexHome "agents\$($e.BaseName).toml"))
    }
    foreach ($e in Get-Children (Join-Path $Preset 'commands') | Where-Object Extension -eq '.md') {
        , @('link', $e.FullName, (Join-Path $ClaudeHome "commands\$($e.Name)"))
    }
    foreach ($kind in 'concepts', 'references', 'hooks') {
        foreach ($e in Get-Children (Join-Path $Preset $kind)) {
            , @('link', $e.FullName, (Join-Path $AgentsHome "$kind\$($e.Name)"))
        }
    }
    # Tool-specific files: top-level files directly, folders one entry at a time.
    # On a machine whose ~/.agents/local/environment names an environment, an entry at the
    # same path under tools/environments/<env>/<tool>/ replaces the default one.
    $machineEnv = Get-MachineEnvironment
    $envDir = if ($machineEnv) { Join-Path (Join-Path $Tools 'environments') $machineEnv } else { $null }
    if ($envDir -and -not (Test-Path -LiteralPath $envDir -PathType Container)) {
        Write-Host "warning: there's no tools/environments/$machineEnv - using the default tool files"
    }
    $homes = @{ claude = $ClaudeHome; codex = $CodexHome; copilot = $CopilotHome }
    foreach ($tool in 'claude', 'codex', 'copilot') {
        $over = if ($envDir) { Join-Path $envDir $tool } else { $null }
        foreach ($e in Get-Children (Join-Path $Tools $tool)) {
            $to = Join-Path $homes[$tool] $e.Name
            if ($e.PSIsContainer) {
                foreach ($c in Get-Children $e.FullName) {
                    , @('link', (Select-Source $c.FullName $over (Join-Path $e.Name $c.Name)), (Join-Path $to $c.Name))
                }
            } else {
                , @('link', (Select-Source $e.FullName $over $e.Name), $to)
            }
        }
    }
}

# The environment named in ~/.agents/local/environment (e.g. "work"), or $null.
# Only a plain name counts, so the file can't point outside tools\environments\.
function Get-MachineEnvironment {
    $file = Join-Path (Join-Path $AgentsHome 'local') 'environment'
    if (-not (Test-Path -LiteralPath $file -PathType Leaf)) { return $null }
    $name = "$(Get-Content -LiteralPath $file -TotalCount 1)".Trim()
    if (-not $name) { return $null }
    if ($name -cmatch '^[A-Za-z0-9_-][A-Za-z0-9._-]*$') { return $name }
    Write-Host "warning: ignoring ~/.agents/local/environment: `"$name`" isn't a plain name - using the default tool files"
    return $null
}

# The environment's entry at $Relative when it has one, else the default.
function Select-Source([string]$Default, [string]$Override, [string]$Relative) {
    if ($Override) {
        $candidate = Join-Path $Override $Relative
        if (Test-Path -LiteralPath $candidate) { return $candidate }
    }
    return $Default
}

# The `agents` command is a bash script; on Windows it runs through Git Bash,
# which Claude Code requires anyway.
function Find-GitBash {
    if ($env:CLAUDE_CODE_GIT_BASH_PATH -and (Test-Path -LiteralPath $env:CLAUDE_CODE_GIT_BASH_PATH)) {
        return $env:CLAUDE_CODE_GIT_BASH_PATH
    }
    $git = Get-Command git -ErrorAction SilentlyContinue
    if (-not $git) { return $null }
    $dir = Split-Path $git.Source
    while ($dir) {
        $candidate = Join-Path $dir 'bin\bash.exe'
        if (Test-Path -LiteralPath $candidate) { return $candidate }
        $dir = Split-Path $dir
    }
    return $null
}

function Install-Shims {
    $script = (Join-Path $Repo 'bin\agents') -replace '\\', '/'
    $cmdShim = Join-Path $BinDir 'agents.cmd'
    $bashShim = Join-Path $BinDir 'agents'
    if ($Uninstall) {
        foreach ($shim in $cmdShim, $bashShim) {
            if ((Test-Path -LiteralPath $shim) -and (Get-Content -LiteralPath $shim -Raw).Contains($script)) {
                Remove-Item -LiteralPath $shim
                Write-Host "removed $shim"
            }
        }
        return
    }

    $bash = Find-GitBash
    if (-not $bash) {
        Write-Warning "Git Bash not found - install Git for Windows to use the 'agents' command"
        return
    }
    New-Item -ItemType Directory -Force -Path $BinDir | Out-Null
    # .cmd for PowerShell/cmd, extensionless script for Git Bash.
    $shims = [ordered]@{
        $cmdShim  = "@echo off`r`n`"$bash`" `"$script`" %*`r`n"
        $bashShim = "#!/usr/bin/env bash`nexec bash `"$script`" `"`$@`"`n"
    }
    foreach ($shim in $shims.Keys) {
        if ((Test-Path -LiteralPath $shim) -and [System.IO.File]::ReadAllText($shim) -eq $shims[$shim]) {
            Write-Host "ok      $shim"
        } else {
            [System.IO.File]::WriteAllText($shim, $shims[$shim])
            Write-Host "shim    $shim"
        }
    }

    # Only touch PATH for the default location; an overridden bin dir is managed by the caller.
    if (-not $env:AGENTS_BIN_DIR) {
        $userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
        if (-not $userPath) { $userPath = '' }
        if (($userPath -split ';') -notcontains $BinDir) {
            [Environment]::SetEnvironmentVariable('Path', (($userPath.TrimEnd(';') + ";$BinDir").TrimStart(';')), 'User')
            Write-Host "added $BinDir to your user PATH - open a new terminal to use 'agents'"
        }
    }
}

# Links into this repo whose target is gone (or all of them on uninstall),
# and generated Codex agents whose source is gone.
function Remove-Stale {
    $candidates = foreach ($dir in $ClaudeHome, $CodexHome, $CopilotHome, $AgentsHome) {
        if (-not (Test-Path -LiteralPath $dir)) { continue }
        foreach ($item in Get-ChildItem -LiteralPath $dir -Force) {
            $item
            if ($item.PSIsContainer -and -not $item.LinkType) {
                Get-ChildItem -LiteralPath $item.FullName -Force -Attributes ReparsePoint -ErrorAction SilentlyContinue
            }
        }
    }
    foreach ($link in $candidates) {
        $target = Get-LinkTarget $link.FullName
        if (-not $target -or -not $target.StartsWith("$Repo\", 'OrdinalIgnoreCase')) { continue }
        if ($Uninstall -or -not (Test-Path -LiteralPath $target)) {
            Remove-Link $link.FullName
            Write-Host "removed $($link.FullName)"
        }
    }
    # Copies made instead of links go the same way, except that an edited copy is moved aside.
    foreach ($to in @($Copies.Keys)) {
        if (-not (Test-Path -LiteralPath $to) -or (Get-LinkTarget $to)) { $Copies.Remove($to); continue }
        if ($Uninstall -or -not (Test-Path -LiteralPath $Copies[$to].Src)) {
            if ((Get-FileHash -LiteralPath $to).Hash -eq $Copies[$to].Hash) {
                Remove-Item -LiteralPath $to -Force
                Write-Host "removed $to"
            } else {
                Move-Aside $to
            }
            $Copies.Remove($to)
        }
    }
    Save-Copies
    foreach ($dir in (Join-Path $ClaudeHome 'skills'), (Join-Path $AgentsHome 'skills')) {
        foreach ($s in Get-Children $dir -Directory) {
            $m = Join-Path $s.FullName $Marker
            if (-not (Test-Path -LiteralPath $m)) { continue }
            $src = (Get-Content -LiteralPath $m -TotalCount 1).Trim()
            if ($Uninstall -or -not (Test-Path -LiteralPath (Join-Path $Preset "skills\$src"))) {
                Remove-Item -LiteralPath $s.FullName -Recurse -Force
                Write-Host "removed $($s.FullName)"
            }
        }
    }
    foreach ($f in Get-Children (Join-Path $CodexHome 'agents') | Where-Object Extension -eq '.toml') {
        $first = Get-Content -LiteralPath $f.FullName -TotalCount 1
        if ($first -match $GeneratedPattern) {
            if ($Uninstall -or -not (Test-Path -LiteralPath (Join-Path $Preset "agents\$($Matches[1])"))) {
                Remove-Item -LiteralPath $f.FullName
                Write-Host "removed $($f.FullName)"
            }
        }
    }
}

if (-not $Uninstall) {
    foreach ($m in Get-Mappings) {
        switch -Wildcard ($m[0]) {
            'codex-agent' { Write-CodexAgent $m[1] $m[2] }
            'skill-*' { Install-Skill $m[0].Substring(6) $m[1] $m[2] }
            default { Install-Link $m[1] $m[2] }
        }
    }
}
Install-Shims
Remove-Stale

$mode = if ($Uninstall) { 'uninstall' } else { 'install' }
Write-Host "Done ($mode)"
