#!/usr/bin/env bash
# Installs the preset for Claude Code, Codex and GitHub Copilot into your home.
# Linux, macOS and WSL. On native Windows use install.ps1.
#
#   ./install.sh              install (safe to re-run)
#   ./install.sh --update     git pull, then install
#   ./install.sh --uninstall  remove everything that points into this repo
set -euo pipefail
shopt -s nullglob

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
. "$REPO_DIR/lib/common.sh"

CLAUDE_HOME="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
CODEX_HOME="${CODEX_HOME:-$HOME/.codex}"
COPILOT_HOME="${COPILOT_HOME:-$HOME/.copilot}"
AGENTS_HOME="$HOME/.agents"
OVERRIDES="$AGENTS_HOME/overrides"   # user-owned runtime controls, never touched
MARKER=".agents-generated"
BIN_DIR="${AGENTS_BIN_DIR:-$HOME/.local/bin}"
STAMP="$(date +%Y%m%d-%H%M%S)"

case "$(uname -s)" in
  MINGW*|MSYS*|CYGWIN*)
    echo "Git Bash detected: ln -s makes copies here. Run install.ps1 from PowerShell instead." >&2
    exit 1 ;;
esac

case "${1:-}" in
  "")          MODE="install" ;;
  --uninstall) MODE="uninstall" ;;
  --update)
    echo "Updating $REPO_DIR"
    # --autostash keeps local edits (e.g. made through ~/.claude) across the pull.
    if ! git -C "$REPO_DIR" pull --rebase --autostash; then
      echo "git pull failed - resolve it in $REPO_DIR, then run ./install.sh" >&2
      exit 1
    fi
    # Re-run from disk so a changed installer takes effect.
    exec bash "$REPO_DIR/install.sh" ;;
  *)
    echo "usage: $0 [--update | --uninstall]" >&2
    exit 1 ;;
esac

move_aside() {
  mv "$1" "$1.bak.$STAMP"
  echo "backup  $1 -> $1.bak.$STAMP"
}

link_item() {
  local src="$1" dst="$2"
  mkdir -p "$(dirname "$dst")"
  if [ -L "$dst" ]; then
    if [ "$(readlink "$dst")" = "$src" ]; then echo "ok      $dst"; return; fi
    rm "$dst"
  elif [ -f "$dst/$MARKER" ]; then
    rm -rf "$dst"
  elif [ -e "$dst" ]; then
    move_aside "$dst"
  fi
  ln -s "$src" "$dst"
  echo "linked  $dst"
}

# Links a skill, or builds a marked copy when an adapter or override applies.
install_skill() {
  local tool="$1" src="$2" dst="$3" tmp
  if ! skill_needs_build "$tool" "$src" "$OVERRIDES"; then link_item "$src" "$dst"; return; fi
  tmp="$(mktemp -d)"
  build_skill "$tool" "$src" "$tmp/skill" "$OVERRIDES"
  echo "$(basename "$src")" > "$tmp/skill/$MARKER"
  if [ -f "$dst/$MARKER" ] && diff -r "$tmp/skill" "$dst" >/dev/null 2>&1; then
    echo "ok      $dst"; rm -rf "$tmp"; return
  fi
  if [ -L "$dst" ]; then rm "$dst"
  elif [ -f "$dst/$MARKER" ]; then rm -rf "$dst"
  elif [ -e "$dst" ]; then move_aside "$dst"
  fi
  mkdir -p "$(dirname "$dst")"
  mv "$tmp/skill" "$dst"
  rm -rf "$tmp"
  echo "built   $dst ($tool adapter/override applied)"
}

write_codex_agent() {
  local src="$1" dst="$2" tmp
  tmp="$(mktemp)"
  if ! codex_agent "$src" > "$tmp"; then
    echo "skipped $dst (body of $src contains ''')" >&2
    rm -f "$tmp"; return
  fi
  mkdir -p "$(dirname "$dst")"
  if [ -f "$dst" ] && cmp -s "$tmp" "$dst"; then echo "ok      $dst"; rm -f "$tmp"; return; fi
  if [ -e "$dst" ] && ! head -1 "$dst" | grep -q '^# Generated by agents'; then move_aside "$dst"; fi
  mv "$tmp" "$dst"
  echo "wrote   $dst"
}

# Links into this repo whose target is gone, and generated Codex agents whose source is gone.
remove_stale() {
  local link target f src
  for link in "$CLAUDE_HOME"/* "$CLAUDE_HOME"/*/* "$CODEX_HOME"/* "$CODEX_HOME"/*/* \
              "$COPILOT_HOME"/* "$COPILOT_HOME"/*/* "$AGENTS_HOME"/*/* "$BIN_DIR/agents"; do
    [ -L "$link" ] || continue
    target="$(readlink "$link")"
    case "$target" in "$REPO_DIR"/*) ;; *) continue ;; esac
    if [ "$MODE" = "uninstall" ] || [ ! -e "$target" ]; then rm "$link"; echo "removed $link"; fi
  done
  for f in "$CLAUDE_HOME"/skills/*/"$MARKER" "$AGENTS_HOME"/skills/*/"$MARKER"; do
    src="$(cat "$f")"
    if [ "$MODE" = "uninstall" ] || [ ! -d "$REPO_DIR/preset/skills/$src" ]; then
      rm -rf "$(dirname "$f")"; echo "removed $(dirname "$f")"
    fi
  done
  for f in "$CODEX_HOME"/agents/*.toml; do
    src="$(sed -n '1s/^# Generated by agents from \(.*\) - edit that file instead\.$/\1/p' "$f")"
    [ -n "$src" ] || continue
    if [ "$MODE" = "uninstall" ] || [ ! -e "$REPO_DIR/preset/agents/$src" ]; then rm "$f"; echo "removed $f"; fi
  done
}

if [ "$MODE" = "install" ]; then
  while IFS=$'\t' read -r mode src dst; do
    case "$mode" in
      link)        link_item "$src" "$dst" ;;
      codex-agent) write_codex_agent "$src" "$dst" ;;
      skill-*)     install_skill "${mode#skill-}" "$src" "$dst" ;;
    esac
  done < <(global_mappings "$REPO_DIR/preset" "$REPO_DIR/tools")

  # The `agents` command (project setup/update).
  chmod +x "$REPO_DIR/bin/agents"
  mkdir -p "$BIN_DIR"
  link_item "$REPO_DIR/bin/agents" "$BIN_DIR/agents"
  case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) echo "note: add $BIN_DIR to your PATH to use the 'agents' command" ;;
  esac
  find "$REPO_DIR/preset/hooks" -type f \( -name '*.sh' -o -name '*.py' \) -exec chmod +x {} + 2>/dev/null || true
fi
remove_stale

echo "Done ($MODE)"
