# Shared helpers for install.sh and bin/agents. Source it; don't run it.
# install.ps1 mirrors the global mapping below - keep the two in sync.

# Value of a frontmatter key in a Markdown file (empty if missing).
frontmatter() {
  awk -v k="$2" '
    { sub(/\r$/, "") }
    NR == 1 { if ($0 != "---") exit; next }
    $0 == "---" { exit }
    index($0, k ":") == 1 {
      v = substr($0, length(k) + 2)
      gsub(/^[ \t]+|[ \t]+$/, "", v)
      gsub(/^["\047]|["\047]$/, "", v)
      print v
      exit
    }
  ' "$1"
}

# Body of a Markdown file without its frontmatter.
body() {
  awk '
    { sub(/\r$/, "") }
    NR == 1 && $0 == "---" { fm = 1; next }
    fm && $0 == "---" { fm = 0; next }
    !fm
  ' "$1"
}

toml_string() {
  local s="${1//\\/\\\\}"
  printf '"%s"' "${s//\"/\\\"}"
}

# Prints a Codex custom agent (TOML) for a subagent Markdown file.
# Fails if the body can't be stored as a TOML literal string.
codex_agent() {
  local src="$1" name desc text
  name="$(frontmatter "$src" name)"
  [ -n "$name" ] || name="$(basename "$src" .md)"
  desc="$(frontmatter "$src" description)"
  text="$(body "$src")"
  case "$text" in *"'''"*) return 1 ;; esac
  printf '# Generated by agents from %s - edit that file instead.\n' "$(basename "$src")"
  printf 'name = %s\n' "$(toml_string "$name")"
  printf 'description = %s\n' "$(toml_string "$desc")"
  printf "developer_instructions = '''\n%s\n'''\n" "$text"
}

# Prints a SKILL.md whose frontmatter has the top-level keys of the given YAML
# files (later files win) merged in. Base keys that are overridden are dropped.
merge_skill_md() {
  local base="$1"; shift
  awk -v base="$base" '
    function flush() { if (key != "") { if (!(key in val)) order[++n] = key; val[key] = buf } key = "" }
    { sub(/\r$/, "") }
    FILENAME != base {
      if (FNR == 1) flush()
      if ($0 ~ /^[A-Za-z0-9_-]+:/) { flush(); key = $0; sub(/:.*/, "", key); buf = $0; next }
      if (key != "" && $0 ~ /^[ \t-]/) { buf = buf "\n" $0; next }
      flush(); next
    }
    FNR == 1 { flush(); if ($0 == "---") { infm = 1; print; next } }
    infm && $0 == "---" { for (i = 1; i <= n; i++) print val[order[i]]; infm = 0; print; next }
    infm && /^[A-Za-z0-9_-]+:/ { k = $0; sub(/:.*/, "", k); skip = (k in val) }
    infm && skip { next }
    { print }
  ' "$@" "$base"
}

# True if a tool's copy of a skill needs to be built rather than linked/copied
# as-is: an adapter in the skill or a user override applies to it.
skill_needs_build() {
  local tool="$1" src="$2" overrides="$3" n
  n="$(basename "$src")"
  case "$tool" in
    claude) [ -f "$src/agents/claude.yaml" ] || [ -f "$overrides/claude/$n.yaml" ] ;;
    codex)  [ -f "$overrides/codex/$n.yaml" ] ;;
    *) return 1 ;;
  esac
}

# Builds a tool's copy of a skill into $3:
#   claude: SKILL.md + agents/claude.yaml (adapter) + overrides/claude/<n>.yaml
#   codex:  overrides/codex/<n>.yaml replaces agents/openai.yaml
build_skill() {
  local tool="$1" src="$2" dst="$3" overrides="$4" n
  local -a extra=()
  n="$(basename "$src")"
  rm -rf "$dst"
  mkdir -p "$(dirname "$dst")"
  cp -R "$src" "$dst"
  case "$tool" in
    claude)
      [ -f "$src/agents/claude.yaml" ] && extra+=("$src/agents/claude.yaml")
      [ -f "$overrides/claude/$n.yaml" ] && extra+=("$overrides/claude/$n.yaml")
      [ ${#extra[@]} -eq 0 ] || merge_skill_md "$src/SKILL.md" "${extra[@]}" > "$dst/SKILL.md" ;;
    codex)
      if [ -f "$overrides/codex/$n.yaml" ]; then
        mkdir -p "$dst/agents"
        cp "$overrides/codex/$n.yaml" "$dst/agents/openai.yaml"
      fi ;;
  esac
}

# Where every preset item goes in the user's home, one "mode<TAB>src<TAB>dst"
# line each. mode is "link", "codex-agent" (generated TOML) or "skill-<tool>"
# (linked, or built when an adapter/override applies).
global_mappings() {
  local preset="$1" tools="$2" e c n tool home
  printf 'link\t%s\t%s\n' "$preset/AGENTS.md" "$CLAUDE_HOME/CLAUDE.md"
  printf 'link\t%s\t%s\n' "$preset/AGENTS.md" "$CODEX_HOME/AGENTS.md"
  printf 'link\t%s\t%s\n' "$preset/AGENTS.md" "$COPILOT_HOME/copilot-instructions.md"
  for e in "$preset"/skills/*/; do
    n="$(basename "$e")"
    printf 'skill-claude\t%s\t%s\n' "${e%/}" "$CLAUDE_HOME/skills/$n"
    printf 'skill-codex\t%s\t%s\n' "${e%/}" "$AGENTS_HOME/skills/$n"   # Codex + Copilot
  done
  for e in "$preset"/agents/*.md; do
    n="$(basename "$e" .md)"
    printf 'link\t%s\t%s\n' "$e" "$CLAUDE_HOME/agents/$n.md"
    printf 'link\t%s\t%s\n' "$e" "$COPILOT_HOME/agents/$n.agent.md"
    printf 'codex-agent\t%s\t%s\n' "$e" "$CODEX_HOME/agents/$n.toml"
  done
  for e in "$preset"/commands/*.md; do
    printf 'link\t%s\t%s\n' "$e" "$CLAUDE_HOME/commands/$(basename "$e")"
  done
  for n in concepts references hooks; do
    for e in "$preset/$n"/*; do
      printf 'link\t%s\t%s\n' "$e" "$AGENTS_HOME/$n/$(basename "$e")"
    done
  done
  # Tool-specific files: top-level files directly, folders one entry at a time.
  # On a machine whose ~/.agents/local/environment names an environment, an entry at the
  # same path under tools/environments/<env>/<tool>/ replaces the default one.
  local env over src
  env="$(machine_environment)"
  if [ -n "$env" ] && [ ! -d "$tools/environments/$env" ]; then
    echo "warning: there's no tools/environments/$env - using the default tool files" >&2
  fi
  for tool in claude codex copilot; do
    case "$tool" in claude) home="$CLAUDE_HOME" ;; codex) home="$CODEX_HOME" ;; copilot) home="$COPILOT_HOME" ;; esac
    over=""
    if [ -n "$env" ]; then over="$tools/environments/$env/$tool"; fi
    for e in "$tools/$tool"/*; do
      n="${e##*/}"
      if [ -d "$e" ]; then
        for c in "$e"/*; do
          src="$c"
          if [ -n "$over" ] && [ -e "$over/$n/${c##*/}" ]; then src="$over/$n/${c##*/}"; fi
          printf 'link\t%s\t%s\n' "$src" "$home/$n/${c##*/}"
        done
      else
        src="$e"
        if [ -n "$over" ] && [ -e "$over/$n" ]; then src="$over/$n"; fi
        printf 'link\t%s\t%s\n' "$src" "$home/$n"
      fi
    done
  done
}

# The environment named in ~/.agents/local/environment (e.g. "work"), or nothing.
# Only a plain name counts, so the file can't point outside tools/environments/.
machine_environment() {
  local file="$AGENTS_HOME/local/environment" name="" LC_ALL=C
  if [ -f "$file" ]; then read -r name < "$file" || true; fi
  name="${name#$'\xEF\xBB\xBF'}"
  name="${name%$'\r'}"
  name="${name%"${name##*[![:space:]]}"}"
  [ -n "$name" ] || return 0
  case "$name" in
    .*|*[!A-Za-z0-9._-]*)
      echo "warning: ignoring ~/.agents/local/environment: \"$name\" isn't a plain name - using the default tool files" >&2
      return 0 ;;
  esac
  printf '%s' "$name"
}
